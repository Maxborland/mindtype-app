def get_text(key: str, lang: str = "ru") -> str:
    """
    Получить перевод по ключу.

    Args:
        key: Ключ перевода
        lang: Код языка (ru, en, de, fr, es, it, pt, zh, ja, ko)

    Returns:
        Переведённая строка или ключ если перевод не найден
    """
    if lang not in TRANSLATIONS:
        lang = "en"  # Fallback на английский

    translations = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    return translations.get(key, TRANSLATIONS["en"].get(key, key))


def get_whisper_language_name(code: str) -> str:
    """
    Получить название языка Whisper по коду.

    Args:
        code: Код языка (ru, en, auto, ...)

    Returns:
        Название языка
    """
    return WHISPER_LANGUAGES.get(code, code)


def get_ui_language_name(code: str) -> str:
    """
    Получить название языка интерфейса по коду.

    Args:
        code: Код языка (ru, en, ...)

    Returns:
        Название языка
    """
    return UI_LANGUAGES.get(code, code)

